#!/usr/bin/env python3
"""Run database/integrity_tests.sql.

Every test must be rejected by the database with the expected message, and the
database must be unchanged afterwards (row counts of every table are compared).

Usage:
    python3 tools/run_integrity_tests.py              # uses the local `mysql` client
    MYSQL_CMD="mysql -h127.0.0.1 -uroot -proot" python3 tools/run_integrity_tests.py
    python3 tools/run_integrity_tests.py --markdown docs/INTEGRITY_TESTS.md
"""
import argparse
import os
import re
import shlex
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MYSQL = shlex.split(os.environ.get("MYSQL_CMD", "mysql"))
DB = os.environ.get("FIR_DB", "fir_ccms")


def run_sql(sql, database=DB):
    proc = subprocess.run(MYSQL + ["--batch", "--skip-column-names", database],
                          input=sql, capture_output=True, text=True)
    return proc.returncode, proc.stdout, proc.stderr.strip()


def row_counts():
    code, out, err = run_sql("SHOW TABLES")
    tables = [t for t in out.split() if t]
    union = " UNION ALL ".join(f"SELECT '{t}', COUNT(*) FROM `{t}`" for t in tables)
    code, out, err = run_sql(union)
    if code != 0:
        raise SystemExit(f"cannot count rows: {err}")
    return dict(line.split("\t") for line in out.strip().splitlines())


def parse(path):
    tests, cur = [], None
    for line in open(path, encoding="utf-8"):
        m = re.match(r"-- (T\d+) \| (.*)", line)
        if m:
            cur = {"id": m.group(1), "rule": m.group(2).strip(), "expect": None, "sql": []}
            tests.append(cur)
            continue
        m = re.match(r"-- Expect: (.*)", line)
        if m and cur:
            cur["expect"] = m.group(1).strip()
            continue
        if cur and not line.startswith("--"):
            cur["sql"].append(line)
    for t in tests:
        t["sql"] = "".join(t["sql"]).strip()
    return tests


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", help="also write the results to this markdown file")
    args = ap.parse_args()

    tests = parse(os.path.join(ROOT, "database", "integrity_tests.sql"))
    before = row_counts()
    results, failed = [], 0
    for t in tests:
        code, _out, err = run_sql(t["sql"])
        message = err.splitlines()[-1] if err else ""
        message = re.sub(r"^ERROR (\d+) \((\w+)\)( at line \d+)?: ", r"ERROR \1: ", message)
        ok = code != 0 and t["expect"].lower() in err.lower()
        failed += 0 if ok else 1
        results.append((t, ok, message))
        print(f"{'PASS' if ok else 'FAIL'}  {t['id']}  {t['rule']}")
        if not ok:
            print(f"      expected: {t['expect']}\n      got:      {message or '(no error: the rule was NOT enforced)'}")
    after = row_counts()
    unchanged = before == after
    print(f"\n{len(tests) - failed}/{len(tests)} rejected as expected; "
          f"database unchanged: {'yes' if unchanged else 'NO'}")

    if args.markdown:
        lines = ["# Integrity test results", "",
                 f"{len(tests) - failed} of {len(tests)} attempts to break a rule were rejected by the database, "
                 f"and the row count of every table was identical before and after the run "
                 f"({'confirmed' if unchanged else 'NOT confirmed'}).", "",
                 "Generated by `python3 tools/run_integrity_tests.py --markdown docs/INTEGRITY_TESTS.md`. "
                 "The SQL of every test is in [`database/integrity_tests.sql`](../database/integrity_tests.sql).", "",
                 "| Test | Rule | Result | Message from MySQL |", "|---|---|---|---|"]
        for t, ok, message in results:
            message = message.replace("|", "\\|")
            lines.append(f"| {t['id']} | {t['rule']} | {'Rejected' if ok else '**NOT rejected**'} | `{message}` |")
        with open(os.path.join(ROOT, args.markdown), "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + "\n")
    sys.exit(0 if failed == 0 and unchanged else 1)


if __name__ == "__main__":
    main()
